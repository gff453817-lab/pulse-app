app.post('/api/videos/:id/like', async (req, res) => {
  if (!must(req, res)) return;

  try {
    const userId = req.u.id;
    const videoId = Number(req.params.id);

    const deleted = await pool.query(
      `
      DELETE FROM likes
      WHERE user_id = $1
      AND video_id = $2
      `,
      [userId, videoId]
    );

    let liked;

    if (deleted.rowCount === 0) {
      await pool.query(
        `
        INSERT INTO likes(user_id, video_id)
        VALUES($1, $2)
        ON CONFLICT DO NOTHING
        `,
        [userId, videoId]
      );

      liked = true;
    } else {
      liked = false;
    }

    const count = await pool.query(
      `
      SELECT COUNT(*) AS c
      FROM likes
      WHERE video_id = $1
      `,
      [videoId]
    );

    res.json({
      liked,
      likes: Number(count.rows[0].c)
    });
  } catch (err) {
    console.error(err);

    res.status(500).json({
      error: 'تعذر تحديث الإعجاب'
    });
  }
});


