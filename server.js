const SEL = `
  SELECT
    v.id,
    v.file,
    v.caption,
    u.name,

    (SELECT COUNT(*)
     FROM likes
     WHERE video_id = v.id) AS likes,

    (SELECT COUNT(*)
     FROM comments
     WHERE video_id = v.id) AS comments,

    EXISTS(
      SELECT 1
      FROM likes
      WHERE video_id = v.id
      AND user_id = $1
    ) AS liked,

    EXISTS(
      SELECT 1
      FROM follows
      WHERE follower = $1
      AND followee = v.user_id
    ) AS following

  FROM videos v
  JOIN users u ON u.id = v.user_id
`;


app.get('/api/feed', async (req, res) => {
  try {
    const me = req.u ? req.u.id : 0;

    const result = await pool.query(
      SEL + `
        ORDER BY v.created DESC
        LIMIT 50
      `,
      [me]
    );

    res.json(result.rows);
  } catch (err) {
    console.error(err);

    res.status(500).json({
      error: 'تعذر تحميل المنشورات'
    });
  }
});


