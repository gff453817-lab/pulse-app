/* رفع ملف من القرص إلى Cloudinary بنفس أسلوب upload_stream الحالي */
const uploadFileToCloudinary = (filePath, resourceType, folder) =>
  new Promise((resolve, reject) => {
    const stream = cloudinary.uploader.upload_stream(
      {
        resource_type: resourceType,
        folder
      },
      (error, result) => {
        if (error) {
          reject(error);
        } else {
          resolve(result);
        }
      }
    );

    const rs = fs.createReadStream(filePath);
    rs.on('error', reject);
    rs.pipe(stream);
  });

/* مقاسات الجودة (للفيديو الأفقي؛ يُقلب الصندوق تلقائيًا للفيديو الطولي) */
const QUALITY = {
  '8k': [7680, 4320],
  '4k': [3840, 2160],
  '2k': [2560, 1440],
  '1k': [1920, 1080],
  '720': [1280, 720]
};

const even = (x) => Math.max(2, Math.round(x / 2) * 2);

/*
  خطة المعالجة — بدون «رفع وهمي»:
  - الدقة: لا تُكبَّر أبدًا (scale ≤ 1) مع الحفاظ على النسبة.
  - الفريمات: تُخفَّض فقط إن كان الأصل أعلى من المطلوب، ولا تُولَّد إطارات وهمية.
*/
function planVideo(src, quality, fpsReq) {
  let w = src.w;
  let h = src.h;
  let scale = 1;
  let belowTarget = false;

  if (QUALITY[quality]) {
    const [bw, bh] = src.w >= src.h ? QUALITY[quality] : [QUALITY[quality][1], QUALITY[quality][0]];
    const raw = Math.min(bw / src.w, bh / src.h);
    belowTarget = raw > 1.001;
    scale = Math.min(1, raw);
  }

  const needScale = scale < 0.999;

  if (needScale) {
    w = even(src.w * scale);
    h = even(src.h * scale);
  }

  let fps = src.fps;
  let needFps = false;

  if (src.fps && fpsReq && src.fps > fpsReq * 1.02) {
    fps = fpsReq;
    needFps = true;
  }

  return { w, h, fps, needScale, needFps, belowTarget, transcode: needScale || needFps };
}

const parseFps = (s) => {
  const [a, b] = String(s || '').split('/').map(Number);
  if (!a || !b) return null;
  return Math.round((a / b) * 100) / 100;
};

const probeVideo = (file) =>
  new Promise((resolve) => {
    execFile(
      FFPROBE,
      [
        '-v', 'error',
        '-show_entries',
        'stream=codec_type,codec_name,width,height,avg_frame_rate,r_frame_rate:stream_tags=rotate:stream_side_data=rotation:format=duration',
        '-of', 'json',
        file
      ],
      { timeout: 30000, maxBuffer: 4 * 1024 * 1024 },
      (err, out) => {
        if (err) return resolve(null);

        try {
          const j = JSON.parse(out);
          const vs = (j.streams || []).find((s) => s.codec_type === 'video');
          const au = (j.streams || []).find((s) => s.codec_type === 'audio');

          if (!vs || !vs.width || !vs.height) return resolve(null);

          let rot = Number(vs.tags && vs.tags.rotate) || 0;
          const sd = (vs.side_data_list || []).find((x) => x.rotation !== undefined);
          if (sd) rot = Number(sd.rotation) || rot;

          const swap = Math.abs(rot) % 180 === 90;

          resolve({
            w: swap ? vs.height : vs.width,
            h: swap ? vs.width : vs.height,
            fps: parseFps(vs.avg_frame_rate) || parseFps(vs.r_frame_rate),
            duration: Number(j.format && j.format.duration) || 0,
            audio: au ? au.codec_name : null
          });
        } catch {
          resolve(null);
        }
      }
    );
  });

const runFfmpeg = (args) =>
  new Promise((resolve, reject) => {
    const p = spawn(FFMPEG, args, { stdio: ['ignore', 'ignore', 'pipe'] });
    let errTail = '';
    let timedOut = false;

    p.stderr.on('data', (d) => {
      errTail = (errTail + d).slice(-2000);
    });

    const t = setTimeout(() => {
      timedOut = true;
      p.kill('SIGKILL');
    }, PROCESS_TIMEOUT_MS);

    p.on('error', (e) => {
      clearTimeout(t);
      reject(e);
    });

    p.on('close', (code) => {
      clearTimeout(t);
      if (code === 0) resolve();
      else reject(new Error(timedOut ? 'ffmpeg timeout' : errTail || 'ffmpeg exit ' + code));
    });
  });

/* معالجة واحدة فقط في نفس الوقت لحماية السيرفر المجاني */
let procChain = Promise.resolve();
const enqueueProcess = (fn) => {
  const p = procChain.then(fn);
  procChain = p.catch(() => {});
  return p;
};

function buildFfmpegArgs(input, output, src, pl) {
  const filters = [];

  if (pl.needScale) filters.push(`scale=${pl.w}:${pl.h}:flags=lanczos`);
  if (pl.needFps) filters.push(`fps=${pl.fps}`);

  const args = [
    '-y', '-hide_banner', '-loglevel', 'error',
    '-i', input,
    '-map', '0:v:0',
    '-map', '0:a:0?',
    '-sn', '-dn'
  ];

  if (filters.length) args.push('-vf', filters.join(','));

  args.push(
    '-c:v', 'libx264',
    '-preset', FFMPEG_PRESET,
    '-crf', '18',
    '-pix_fmt', 'yuv420p',
    '-threads', FFMPEG_THREADS
  );

  /* الصوت: نسخ مباشر إن كان AAC (بدون فقد)، وإلا تحويل إلى AAC بجودة عالية */
  if (src.audio === 'aac') args.push('-c:a', 'copy');
  else args.push('-c:a', 'aac', '-b:a', '192k');

  args.push('-movflags', '+faststart', output);

  return args;
}

/* مهام الرفع في الذاكرة (يتابعها العميل عبر /api/videos/jobs/:id) */
const jobs = new Map();

setInterval(() => {
  const cutoff = Date.now() - 15 * 60 * 1000;
  for (const [id, j] of jobs) {
    if (j.created < cutoff && (j.status === 'done' || j.status === 'error')) jobs.delete(id);
  }
}, 5 * 60 * 1000).unref();

async function runVideoJob(job, file, caption, quality, fpsReq) {
  const tmp = [file.path];

  try {
    job.status = 'processing';

    const src = await probeVideo(file.path);

    let uploadPath = file.path;
    let uploadSize = file.size;
    let processed = false;
    let note = '';
    let orig = null;
    let final = null;

    if (!src) {
      note = 'تعذّر قراءة معلومات الفيديو، فنُشر كما هو دون تغيير.';
    } else {
      orig = { w: src.w, h: src.h, fps: src.fps };
      final = { w: src.w, h: src.h, fps: src.fps };

      const pl = planVideo(src, quality, fpsReq);

      if (pl.transcode) {
        if (src.w * src.h > MAX_PROCESS_PIXELS || src.duration > MAX_PROCESS_SECONDS) {
          note = 'حجم الفيديو أو مدته أكبر من حد المعالجة على هذا الخادم، فنُشر بجودته الأصلية.';
        } else {
          const out = path.join(os.tmpdir(), 'pulse-out-' + crypto.randomBytes(8).toString('hex') + '.mp4');
          tmp.push(out);

          try {
            await enqueueProcess(() => runFfmpeg(buildFfmpegArgs(file.path, out, src, pl)));

            const outSize = fs.statSync(out).size;

            if (outSize > CLOUDINARY_MAX_BYTES) {
              note = 'الناتج بعد المعالجة أكبر من حد الرفع، فنُشر الفيديو بجودته الأصلية.';
            } else {
              uploadPath = out;
              uploadSize = outSize;
              processed = true;

              const o = await probeVideo(out);
              final = o
                ? { w: o.w, h: o.h, fps: o.fps || pl.fps }
                : { w: pl.w, h: pl.h, fps: pl.fps };
            }
          } catch (e) {
            console.error('فشل FFmpeg:', e.message);
            note = 'تعذّرت معالجة الفيديو على الخادم، فنُشر بجودته الأصلية.';
          }
        }
      }

      if (!processed && !note && pl.belowTarget) {
        note = 'الفيديو الأصلي أقل من الجودة المطلوبة، فنُشر بدقته الأصلية دون تكبير وهمي.';
      }
    }

    job.status = 'uploading';

    const uploaded = await uploadFileToCloudinary(uploadPath, 'video', 'pulse');

    const meta = {
      orig,
      requested: { quality, fps: fpsReq },
      final,
      duration: src ? Math.round(src.duration * 10) / 10 : null,
      size_orig: file.size,
      size_final: uploadSize,
      processed
    };

    await pool.query(
      `
      INSERT INTO videos(user_id, file, caption, meta)
      VALUES($1, $2, $3, $4)
      `,
      [job.userId, uploaded.secure_url, caption, JSON.stringify(meta)]
    );

    job.result = { orig, requested: meta.requested, final, processed, note };
    job.status = 'done';
  } catch (err) {
    console.error(err);
    job.status = 'error';
    job.error = 'تعذر رفع الفيديو';
  } finally {
    tmp.forEach(rmFile);
  }
}

app.post(
  '/api/videos',
  (req, res, next) => (must(req, res) ? next() : 0),
  up.single('video'),
  async (req, res) => {
    try {
      if (!req.file) {
        return res.status(400).json({
          error: 'اختر ملف فيديو'
        });
      }

      let busy = 0;
      for (const j of jobs.values()) {
        if (j.userId === req.u.id && (j.status === 'processing' || j.status === 'uploading')) busy++;
      }

      if (busy >= 1) {
        rmFile(req.file.path);
        return res.status(429).json({
          error: 'لديك فيديو قيد المعالجة بالفعل، انتظر حتى ينتهي'
        });
      }

      const quality = QUALITY[req.body.quality] ? req.body.quality : 'auto';
      const fpsReq = Number(req.body.fps) === 30 ? 30 : 60;
      const caption = String(req.body.caption || '').slice(0, 200);

      const id = crypto.randomBytes(8).toString('hex');
      const job = { id, userId: req.u.id, status: 'processing', created: Date.now() };
      jobs.set(id, job);

      runVideoJob(job, req.file, caption, quality, fpsReq);

      res.json({
        ok: true,
        job: id
      });
    } catch (err) {
      rmFile(req.file && req.file.path);
      console.error(err);

      res.status(500).json({
        error: 'تعذر رفع الفيديو'
      });
    }
  }
);

