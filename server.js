/* حذف ملف القصة من Cloudinary — فقط إن كان داخل مجلد pulse/stories (آمن) */
const destroyStoryAsset = (row) => {
  if (!row.public_id || !row.public_id.startsWith('pulse/stories/')) {
    return Promise.resolve();
  }

  return cloudinary.uploader
    .destroy(row.public_id, {
      resource_type: row.type === 'video' ? 'video' : 'image',
      invalidate: true
    })
    .catch((e) => console.error('تعذر حذف ملف القصة من Cloudinary:', e.message || e));
};

/* القصص النشطة فقط (expires_at > NOW())، مجمّعة حسب المستخدم */
app.get('/api/stories', async (req, res) => {
  try {
    const me = req.u ? req.u.id : 0;

    // المسجّل: قصصه + قصص من يتابعهم. الزائر: القصص العامة النشطة.
    const scope = req.u
      ? `AND (s.user_id = $1 OR EXISTS(
           SELECT 1 FROM follows
           WHERE follower = $1 AND followee = s.user_id
         ))`
      : '';

    const result = await pool.query(
      `
      SELECT
        s.id,
        s.file,
        s.type,
        s.created_at,
        s.expires_at,
        u.name,
        (s.user_id = $1) AS mine
      FROM stories s
      JOIN users u ON u.id = s.user_id
      WHERE s.expires_at > NOW()
      ${scope}
      ORDER BY s.created_at DESC
      LIMIT 500
      `,
      [me]
    );

    const map = new Map();

    for (const row of result.rows.reverse()) {
      if (!map.has(row.name)) {
        map.set(row.name, { name: row.name, mine: row.mine, stories: [] });
      }

      map.get(row.name).stories.push({
        id: row.id,
        file: row.file,
        type: row.type,
        created_at: row.created_at,
        expires_at: row.expires_at
      });
    }

    const last = (g) => new Date(g.stories[g.stories.length - 1].created_at).getTime();

    const groups = [...map.values()].sort((a, b) => {
      if (a.mine !== b.mine) return a.mine ? -1 : 1;
      return last(b) - last(a);
    });

    res.json(groups);
  } catch (err) {
    console.error(err);

    res.status(500).json({
      error: 'تعذر تحميل القصص'
    });
  }
});

