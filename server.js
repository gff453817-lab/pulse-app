app.delete('/api/stories/:id', async (req, res) => {
  if (!must(req, res)) return;

  try {
    const id = Number(req.params.id);

    if (!Number.isInteger(id)) {
      return res.status(400).json({
        error: 'معرّف غير صالح'
      });
    }

    const result = await pool.query(
      `
      SELECT id, user_id, type, public_id
      FROM stories
      WHERE id = $1
      `,
      [id]
    );

    if (result.rowCount === 0) {
      return res.status(404).json({
        error: 'القصة غير موجودة'
      });
    }

    const story = result.rows[0];

    if (story.user_id !== req.u.id) {
      return res.status(403).json({
        error: 'لا يمكنك حذف هذه القصة'
      });
    }

    await pool.query(`DELETE FROM stories WHERE id = $1`, [id]);

    destroyStoryAsset(story);

    res.json({
      ok: true
    });
  } catch (err) {
    console.error(err);

    res.status(500).json({
      error: 'تعذر حذف القصة'
    });
  }
});

/* تنظيف دوري داخل التطبيق (بدون Cron خارجي) */
async function cleanupStories() {
  try {
    const result = await pool.query(
      `
      DELETE FROM stories
      WHERE expires_at <= NOW()
      RETURNING type, public_id
      `
    );

    for (const row of result.rows) {
      await destroyStoryAsset(row);
    }

    if (result.rowCount) {
      console.log(`تم حذف ${result.rowCount} قصة منتهية.`);
    }
  } catch (err) {
    console.error('تعذر تنظيف القصص المنتهية:', err.message || err);
  }
}


