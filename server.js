/* =========================
   Follow
========================= */

app.post('/api/users/:name/follow', async (req, res) => {
  if (!must(req, res)) return;

  try {
    const target = await pool.query(
      `
      SELECT id
      FROM users
      WHERE name = $1
      `,
      [req.params.name]
    );

    const t = target.rows[0];

    if (!t || t.id === req.u.id) {
      return res.status(400).json({
        error: 'غير ممكن'
      });
    }

    const deleted = await pool.query(
      `
      DELETE FROM follows
      WHERE follower = $1
      AND followee = $2
      `,
      [
        req.u.id,
        t.id
      ]
    );

    let following;

    if (deleted.rowCount === 0) {
      await pool.query(
        `
        INSERT INTO follows(follower, followee)
        VALUES($1, $2)
        ON CONFLICT DO NOTHING
        `,
        [
          req.u.id,
          t.id
        ]
      );

      following = true;
    } else {
      following = false;
    }

    res.json({
      following
    });
  } catch (err) {
    console.error(err);

    res.status(500).json({
      error: 'تعذر تحديث المتابعة'
    });
  }
});


/* =========================
   User Profile
========================= */

app.get('/api/users/:name', async (req, res) => {
  try {
    const userResult = await pool.query(
      `
      SELECT id, name
      FROM users
      WHERE name = $1
      `,
      [req.params.name]
    );

    const u = userResult.rows[0];

    if (!u) {
      return res.status(404).json({
        error: 'غير موجود'
      });
    }

    const followers = await pool.query(
      `
      SELECT COUNT(*) AS c
      FROM follows
      WHERE followee = $1
      `,
      [u.id]
    );

    const following = await pool.query(
      `
      SELECT COUNT(*) AS c
      FROM follows
      WHERE follower = $1
      `,
      [u.id]
    );

    const videos = await pool.query(
      SEL +
        `
        WHERE v.user_id = $2
        ORDER BY v.created DESC
        `,
      [
        req.u ? req.u.id : 0,
        u.id
      ]
    );

    res.json({
      name: u.name,
      followers: Number(followers.rows[0].c),
      following: Number(following.rows[0].c),
      videos: videos.rows
    });
  } catch (err) {
    console.error(err);

    res.status(500).json({
      error: 'تعذر تحميل الحساب'
    });
  }
});


