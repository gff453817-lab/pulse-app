
const express = require('express');
const { Pool } = require('pg');
const bcrypt = require('bcryptjs');
const jwt = require('jsonwebtoken');
const multer = require('multer');
const path = require('path');
const fs = require('fs');
const crypto = require('crypto');

const SECRET =
  process.env.JWT_SECRET || crypto.randomBytes(32).toString('hex');

if (!process.env.JWT_SECRET) {
  console.warn(
    'تنبيه: JWT_SECRET غير مضبوط، سيتسجّل خروج الجميع عند كل إعادة تشغيل.'
  );
}

if (!process.env.DATABASE_URL) {
  console.error('خطأ: DATABASE_URL غير مضبوط.');
  process.exit(1);
}

const pool = new Pool({
  connectionString: process.env.DATABASE_URL,
  ssl: {
    rejectUnauthorized: false
  }
});

fs.mkdirSync('uploads', { recursive: true });

async function initDB() {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS users (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT UNIQUE NOT NULL,
      pass TEXT NOT NULL
    );

    CREATE TABLE IF NOT EXISTS videos (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      file TEXT NOT NULL,
      caption TEXT,
      created BIGINT DEFAULT EXTRACT(EPOCH FROM NOW())
    );

    CREATE TABLE IF NOT EXISTS likes (
      user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      video_id INTEGER NOT NULL REFERENCES videos(id) ON DELETE CASCADE,
      PRIMARY KEY (user_id, video_id)
    );

    CREATE TABLE IF NOT EXISTS comments (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      video_id INTEGER NOT NULL REFERENCES videos(id) ON DELETE CASCADE,
      body TEXT NOT NULL,
      created BIGINT DEFAULT EXTRACT(EPOCH FROM NOW())
    );

    CREATE TABLE IF NOT EXISTS follows (
      follower INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      followee INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      PRIMARY KEY (follower, followee)
    );
  `);

  console.log('تم الاتصال بقاعدة بيانات Neon بنجاح.');
}
const app = express();

app.use(express.json());

app.use((req, res, next) => {
  try {
    const auth = (req.headers.authorization || '').replace('Bearer ', '');
    req.u = jwt.verify(auth, SECRET);
  } catch {
    req.u = null;
  }

  next();
});

const must = (req, res) =>
  req.u ||
  (res.status(401).json({ error: 'سجّل الدخول أولًا' }), null);

const up = multer({
  storage: multer.diskStorage({
    destination: 'uploads',
    filename: (req, file, cb) => {
      cb(
        null,
        crypto.randomUUID() +
          path.extname(file.originalname).toLowerCase().slice(0, 6)
      );
    }
  }),
  limits: {
    fileSize: 100 * 1024 * 1024
  },
  fileFilter: (req, file, cb) => {
    cb(null, /^video\//.test(file.mimetype));
  }
});

const token = (u) =>
  jwt.sign(
    {
      id: u.id,
      name: u.name
    },
    SECRET,
    {
      expiresIn: '30d'
    }
  );

const cred = (b) =>
  /^[A-Za-z0-9_]{3,20}$/.test(b.name || '') &&
  (b.pass || '').length >= 6;


/* =========================
   Register
========================= */

app.post('/api/register', async (req, res) => {
  if (!cred(req.body)) {
    return res.status(400).json({
      error:
        'الاسم 3-20 حرفًا إنجليزيًا/أرقام/_ وكلمة المرور 6 على الأقل'
    });
  }

  try {
    const hashed = bcrypt.hashSync(req.body.pass, 10);

    const result = await pool.query(
      `
      INSERT INTO users(name, pass)
      VALUES($1, $2)
      RETURNING id, name
      `,
      [req.body.name, hashed]
    );

    const u = result.rows[0];

    res.json({
      token: token(u),
      name: u.name
    });
  } catch (err) {
    if (err.code === '23505') {
      return res.status(409).json({
        error: 'الاسم مستخدم'
      });
    }

    console.error(err);
    res.status(500).json({
      error: 'حدث خطأ في الخادم'
    });
  }
});


/* =========================
   Login
========================= */

app.post('/api/login', async (req, res) => {
  try {
    const result = await pool.query(
      'SELECT * FROM users WHERE name = $1',
      [req.body.name || '']
    );

    const u = result.rows[0];

    if (!u || !bcrypt.compareSync(req.body.pass || '', u.pass)) {
      return res.status(401).json({
        error: 'بيانات الدخول غير صحيحة'
      });
    }

    res.json({
      token: token(u),
      name: u.name
    });
  } catch (err) {
    console.error(err);

    res.status(500).json({
      error: 'حدث خطأ في الخادم'
    });
  }
});


